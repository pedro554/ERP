CREATE TABLE USUARIO (
    ID INTEGER NOT NULL,
    NOME VARCHAR(20),
    LOGIN VARCHAR(20),
    SENHA VARCHAR(20),
    ATIVO BOOLEAN,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID));

CREATE UNIQUE INDEX PK_USUARIO ON USUARIO (ID);

CREATE TABLE EMPRESA (
    CD_EMPRESA INTEGER NOT NULL,
    ST_ATIVO BOOLEAN NOT NULL,
    NM_EMPRESA VARCHAR(50) NOT NULL,
    DS_OBSERVACAO VARCHAR(500),
    DT_CADASTRO TIMESTAMP,
CONSTRAINT PK_EMPRESA PRIMARY KEY ( CD_EMPRESA));

CREATE SEQUENCE SEQ_EMPRESA START WITH 0 INCREMENT BY 1;

